// Plantillas propias (Text > Create Template): se guardan en las preferencias y se suman a las integradas.
inline QList<Snippet>& snippetStore ()
{
    static QList<Snippet> all; static bool init = false;
    if (!init)
    {
        init = true; all = builtinSnippets();
        for (const QString& e : QSettings().value("snippets/user").toStringList()) { const QStringList p = e.split('\x1f'); if (p.size() == 3) all.append({p[0], p[1], p[2]}); }
    }
    return all;
}
inline const QList<Snippet>& snippets () { return snippetStore(); }
inline void addUserSnippet (const Snippet& s)
{
    QSettings st; QStringList l = st.value("snippets/user").toStringList();
    for (int i = l.size() - 1; i >= 0; --i) if (l[i].section('\x1f', 0, 0).compare(s.trigger, Qt::CaseInsensitive) == 0) l.removeAt(i);       // misma abreviatura: se reemplaza
    l << (s.trigger + '\x1f' + s.title + '\x1f' + s.body); st.setValue("snippets/user", l);
    auto& all = snippetStore(); for (int i = all.size() - 1; i >= builtinSnippets().size(); --i) if (all[i].trigger.compare(s.trigger, Qt::CaseInsensitive) == 0) all.removeAt(i);
    all.append(s);
}
